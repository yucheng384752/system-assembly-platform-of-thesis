import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

/** @typedef {(command: string, args: string[], options: import('node:child_process').SpawnSyncOptionsWithStringEncoding) =>
 * {status?: number | null, stdout?: string | Buffer | null, stderr?: string | Buffer | null, error?: Error}} Run */

/** @param {Buffer | string} data */
const sha256 = data => createHash('sha256').update(data).digest('hex');
/** @param {string} a @param {string} b */
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const SERVICES = ['postgres', 'backend', 'init', 'guard', 'proxy'];
const IMAGE_ID = /^sha256:[a-f0-9]{64}$/;

/** The `image:` of each service that names one; backend, init and guard are built, so they have none.
 * @param {string} compose */
export function composeImages(compose) {
  /** @type {Map<string, string>} */
  const images = new Map();
  let service = '';
  for (const line of compose.split('\n')) {
    const header = /^  ([a-z][a-z0-9_-]*):\s*$/.exec(line);
    if (header) service = header[1];
    const image = /^    image:\s*(\S+)\s*$/.exec(line);
    if (image && service) images.set(service, image[1]);
    if (/^[a-z]/.test(line)) service = '';
  }
  return images;
}

/** Add offline images to an assembled directory. Needs Docker and network, so it is a release step, not part of assembly.
 * @param {string} dir assembled output of assembleSystem
 * @param {{systemVersion?: string, run?: Run}} [options] */
export async function bundleImages(dir, { systemVersion, run = spawnSync } = {}) {
  if (!systemVersion || !/^[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9.-]+)?$/.test(systemVersion)) throw new Error('必須提供合法的 systemVersion（例如 1.0.0）');
  const manifestFile = path.join(dir, 'system-manifest.json');
  const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
  if (manifest.format !== 'composer-system-assembly') throw new Error('不是系統組裝目錄');
  if (manifest.images || manifest.systemVersion) throw new Error('已含映像或 systemVersion；不覆寫，請用新的組裝目錄');
  const pulled = composeImages(await readFile(path.join(dir, 'deployment/docker-compose.yml'), 'utf8'));
  for (const service of ['postgres', 'proxy']) if (!pulled.has(service)) throw new Error(`Compose 缺少 ${service} 的 image`);
  for (const service of ['backend', 'init', 'guard']) if (pulled.has(service)) throw new Error(`${service} 應由 build 產生，不應指定 image`);

  /** @param {string[]} args @param {string} [cwd] */
  const docker = (args, cwd) => {
    const result = run('docker', args, { encoding: 'utf8', cwd, maxBuffer: 1 << 26 });
    if (result.error || result.status !== 0) throw new Error(`docker ${args[0]} 失敗：${String(result.stderr ?? result.error?.message ?? '').trim().slice(0, 300)}`);
    return String(result.stdout ?? '').trim();
  };
  const built = `composer-${manifest.systemId}-backend:${systemVersion}`;
  // The .dockerignore generated by assembly keeps secrets, license and .env out of this context.
  docker(['build', '--file', 'deployment/backend.Dockerfile', '--tag', built, '.'], dir);
  for (const service of ['postgres', 'proxy']) docker(['pull', /** @type {string} */ (pulled.get(service))]);

  await mkdir(path.join(dir, 'images'));
  const wanted = [
    { name: 'backend', tag: built, services: ['backend', 'init', 'guard'] },
    { name: 'postgres', tag: /** @type {string} */ (pulled.get('postgres')), services: ['postgres'] },
    { name: 'proxy', tag: /** @type {string} */ (pulled.get('proxy')), services: ['proxy'] },
  ];
  const images = [];
  const added = [];
  for (const { name, tag, services } of wanted) {
    const id = docker(['image', 'inspect', '--format', '{{.Id}}', tag]);
    if (!IMAGE_ID.test(id)) throw new Error(`映像 ID 格式不符：${tag}`);
    const archive = `images/${name}.tar`;
    docker(['save', '--output', path.join(dir, archive), tag]);
    const data = await readFile(path.join(dir, archive));
    images.push({ id, tag, archive, services });
    added.push({ path: archive, sha256: sha256(data), bytes: data.length, role: 'image-archive' });
  }
  const covered = images.flatMap(image => image.services).sort();
  if (JSON.stringify(covered) !== JSON.stringify([...SERVICES].sort())) throw new Error('映像未覆蓋全部 services');
  const updated = { ...manifest, systemVersion, images,
    files: [...manifest.files, ...added].sort((a, b) => compare(a.path, b.path)) };
  await writeFile(manifestFile, Buffer.from(JSON.stringify(updated, null, 2) + '\n'));
  return updated;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 5 || process.argv[3] !== '--system-version') throw new Error('用法：node services/package/bundle-images.mjs <組裝目錄> --system-version <x.y.z>');
    await bundleImages(path.resolve(process.argv[2]), { systemVersion: process.argv[4] });
  } catch (error) { console.error(error instanceof Error ? error.message : error); process.exitCode = 1; }
}
